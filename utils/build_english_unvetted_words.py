#!/usr/bin/env python3
"""
List the English dictionary words no vetted word list backs, near a common word.

data.json's curated band came from a web corpus, so it carries entries like "thos",
"amd", "snd" and "yoy" that aren't English words a person means. A slip that lands
on one ("thos" for "this") reads as a known word and space leaves it alone. The
Latin provider corrects such a word on space when a one-edit word is far more
common, but only for the words in this list: rare real words ("snide", "plop",
"wager") sit at the same frequencies and must stay as typed.

A word is vetted when SCOWL up to size 70 lists it in any spelling (American,
British, Canadian, Australian, their variants, proper names, abbreviations,
contractions, upper-case forms), when it's in utils/english_modern_terms.txt, or
when utils/english_chat_terms.txt keeps it (idk, tbh). SCOWL above 70 isn't
trusted as real words (it carries "accomodate" and "wich").

Only words with a one-edit (Damerau) neighbor at --common-frequency or above are
written, since the provider needs that neighbor anyway; that keeps the asset small.

Usage:
    python3 utils/build_english_unvetted_words.py \\
        --base app/src/main/assets/ime/dict/data.json \\
        --supplemental app/src/main/assets/ime/dict/en_supplemental.json \\
        --scowl-final /path/to/scowl-2020.12.07/final \\
        --modern-terms utils/english_modern_terms.txt \\
        --chat-terms utils/english_chat_terms.txt \\
        --output app/src/main/assets/ime/dict/en_unvetted.txt
"""

import argparse
import json
import re
import sys
from pathlib import Path

WORD_RE = re.compile(r"^[a-z](?:[a-z'-]*[a-z])?$")
SCOWL_MAX_SIZE = 70
SCOWL_NAME_RE = re.compile(r"^(?P<category>[a-z_0-9-]+)\.(?P<size>\d+)$")
SCOWL_SKIPPED_CATEGORIES = ("special-hacker", "special-roman-numerals")
# Raw data.json frequency (0-255) a neighbor needs before a word is worth listing. The
# provider's own fix threshold is 0.78 of the blended scale; raw 180 leaves room for the
# Zipf overlay moving words up.
DEFAULT_COMMON_FREQUENCY = 180
HEADER = """\
# English dictionary words that no vetted list backs (SCOWL up to size 70, the modern-terms and
# chat-terms lists), one per line, each one edit from a common word. Generated by
# utils/build_english_unvetted_words.py; don't edit by hand. The Latin provider lets space
# correct a rare word from this list to a far more common one-edit word ("thos" to "this").
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", required=True, type=Path, help="data.json")
    parser.add_argument("--supplemental", required=True, type=Path, help="en_supplemental.json")
    parser.add_argument("--scowl-final", required=True, type=Path, help="SCOWL final/ directory")
    parser.add_argument("--modern-terms", required=True, type=Path, help="One lowercase term per line")
    parser.add_argument("--chat-terms", required=True, type=Path, help="One lowercase term per line")
    parser.add_argument("--common-frequency", type=int, default=DEFAULT_COMMON_FREQUENCY)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    for path in (args.base, args.supplemental, args.modern_terms, args.chat_terms):
        if not path.is_file():
            print(f"error: not found: {path}", file=sys.stderr)
            return 1
    if not args.scowl_final.is_dir():
        print(f"error: SCOWL final directory not found: {args.scowl_final}", file=sys.stderr)
        return 1

    frequencies = load_frequencies(args.base)
    for word, frequency in load_frequencies(args.supplemental).items():
        frequencies.setdefault(word, frequency)
    vetted = load_scowl(args.scowl_final) | load_terms(args.modern_terms) | load_terms(args.chat_terms)
    common = {word for word, frequency in frequencies.items() if frequency >= args.common_frequency}
    index = delete_index(common)

    unvetted = sorted(
        word
        for word in frequencies
        if word not in vetted and len(word) >= 3 and has_common_neighbor(word, index)
    )
    args.output.write_text(HEADER + "".join(f"{word}\n" for word in unvetted), encoding="utf-8", newline="\n")
    print(f"{len(unvetted)} unvetted words near one of {len(common)} common words -> {args.output}")
    return 0


def load_frequencies(path: Path) -> dict[str, int]:
    with path.open("r", encoding="utf-8") as fh:
        raw = json.load(fh)
    return {word: int(frequency) for word, frequency in raw.items() if WORD_RE.match(word)}


def load_scowl(final_dir: Path) -> set[str]:
    words: set[str] = set()
    for path in sorted(final_dir.iterdir()):
        match = SCOWL_NAME_RE.match(path.name)
        if match is None or int(match.group("size")) > SCOWL_MAX_SIZE:
            continue
        if match.group("category") in SCOWL_SKIPPED_CATEGORIES:
            continue
        with path.open("r", encoding="latin-1") as fh:
            for raw in fh:
                word = raw.strip().lower()
                if word:
                    words.add(word)
    return words


def load_terms(path: Path) -> set[str]:
    with path.open("r", encoding="utf-8") as fh:
        return {line.strip().lower() for line in fh if line.strip() and not line.startswith("#")}


def deletes(word: str) -> set[str]:
    return {word[:i] + word[i + 1:] for i in range(len(word))}


def delete_index(words: set[str]) -> dict[str, set[str]]:
    index: dict[str, set[str]] = {}
    for word in words:
        for key in deletes(word) | {word}:
            index.setdefault(key, set()).add(word)
    return index


def has_common_neighbor(word: str, index: dict[str, set[str]]) -> bool:
    for key in deletes(word) | {word}:
        for candidate in index.get(key, ()):
            if candidate != word and damerau_distance_is_one(word, candidate):
                return True
    return False


def damerau_distance_is_one(left: str, right: str) -> bool:
    if abs(len(left) - len(right)) > 1:
        return False
    if len(left) == len(right):
        differences = [i for i in range(len(left)) if left[i] != right[i]]
        if len(differences) == 1:
            return True
        return (
            len(differences) == 2
            and differences[1] == differences[0] + 1
            and left[differences[0]] == right[differences[1]]
            and left[differences[1]] == right[differences[0]]
        )
    shorter, longer = (left, right) if len(left) < len(right) else (right, left)
    return any(longer[:i] + longer[i + 1:] == shorter for i in range(len(longer)))


if __name__ == "__main__":
    sys.exit(main())
